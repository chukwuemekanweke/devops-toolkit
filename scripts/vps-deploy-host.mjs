#!/usr/bin/env node
// Constrained host-side deployment interface. Invoked as root only through the
// stack-bound SSH forced command (deploy) or the stack systemd unit
// (start/stop). It accepts no shell fragments: the operation and stack are fixed
// arguments, and the deployment request arrives as one bounded JSON document on
// stdin that is validated against the root-owned host stack registry.
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { DeployError, validateStackName } from "./vps-deploy/contract.mjs";
import { DockerCompose } from "./vps-deploy/docker.mjs";
import { DeploymentEngine } from "./vps-deploy/engine.mjs";
import { defaultRegistryDirectory, loadRegistry, loadRuntimeSecretInstance } from "./vps-deploy/registry.mjs";
import { SystemdRuntimeSecrets } from "./vps-deploy/secrets.mjs";
import { StackState } from "./vps-deploy/state.mjs";

const operations = new Set(["deploy", "start", "stop", "boot-dropin"]);

export function parseArguments(argv) {
  const [operation, flag, stack, ...rest] = argv;
  if (!operations.has(operation) || flag !== "--stack" || rest.length > 0) {
    throw new DeployError("usage", "usage: vps-deploy-host <deploy|start|stop|boot-dropin> --stack <stack-name>");
  }
  return { operation, stack: validateStackName(stack) };
}

export async function readInput(stream, limit = 4 * 1024 * 1024 + 1024) {
  const chunks = [];
  let size = 0;
  for await (const chunk of stream) {
    size += chunk.length;
    if (size > limit) throw new DeployError("validation", "deployment request exceeds 4 MiB");
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString("utf8");
}

export function bootDropin(registry) {
  const units = [...registry.secretServices.values()].filter((entry) => entry.startAtBoot).map((entry) => `runtime-secrets-initialize@${entry.instance}.service`).sort();
  const lines = ["# Generated by vps-deploy-host boot-dropin. Install as", `# /etc/systemd/system/vps-deploy-stack@${registry.stackName}.service.d/runtime-secrets.conf`, "[Unit]"];
  if (units.length) {
    lines.push(`Requires=${units.join(" ")}`, `After=${units.join(" ")}`);
  } else {
    lines.push("# This stack has no boot-time runtime-secret services.");
  }
  return `${lines.join("\n")}\n`;
}

export function createEngine(stack, overrides = {}) {
  const registryDirectory = overrides.registryDirectory ?? defaultRegistryDirectory;
  return new DeploymentEngine({
    stack,
    docker: overrides.docker ?? new DockerCompose(),
    secrets: overrides.secrets ?? new SystemdRuntimeSecrets(),
    loadRegistry: overrides.loadRegistry ?? ((name) => loadRegistry(name, { directory: registryDirectory })),
    loadInstance: overrides.loadInstance ?? ((id) => loadRuntimeSecretInstance(id)),
    createState: overrides.createState ?? ((root) => new StackState(root)),
    progress: overrides.progress ?? ((event) => process.stderr.write(`${JSON.stringify(event)}\n`)),
    ...(overrides.engine ?? {}),
  });
}

export async function main(argv = process.argv.slice(2), { stdin = process.stdin, overrides = {} } = {}) {
  const { operation, stack } = parseArguments(argv);
  const engine = createEngine(stack, overrides);
  if (operation === "deploy") return await engine.deploy(await readInput(stdin));
  if (operation === "start") return await engine.start();
  if (operation === "stop") return await engine.stop();
  return { ok: true, dropin: bootDropin(await engine.deps.loadRegistry(stack)) };
}

function safeWrite(stream, text) {
  try { stream.write(text); } catch { /* the SSH client may have disconnected; state is recorded on the host */ }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  // A dropped SSH connection must not interrupt a deployment between state transitions.
  process.on("SIGHUP", () => {});
  process.on("SIGPIPE", () => {});
  process.stdout.on("error", () => {});
  process.stderr.on("error", () => {});
  main().then((result) => {
    if (result.dropin !== undefined) safeWrite(process.stdout, result.dropin);
    else safeWrite(process.stdout, `${JSON.stringify(result)}\n`);
    process.exitCode = result.ok ? 0 : (result.status === "restored-after-failure" ? 3 : 1);
  }).catch((error) => {
    const safe = error instanceof DeployError ? { category: error.category, message: error.message.slice(0, 500) } : { category: "internal", message: "vps-deploy-host failed" };
    safeWrite(process.stdout, `${JSON.stringify({ ok: false, status: "failed", failure: safe })}\n`);
    process.exitCode = error instanceof DeployError && error.category === "usage" ? 2 : 1;
  });
}
